import type { CatalogCapabilityRoute, CatalogRole, ContextPackId, RoleId } from "./types.js";

const parentPromptPaths = ["AGENTS.md", "APP_AGENTS.md"];
const route = (id: string, when: string): CatalogCapabilityRoute => ({ id, when });

function role(
  id: RoleId,
  name: string,
  prompt: string,
  scope: string,
  contextPackIds: ContextPackId[],
  skillRoutes: CatalogCapabilityRoute[],
  toolRoutes: CatalogCapabilityRoute[],
  capabilityIds: string[],
  outputPathPrefixes: string[],
  /** Fresh-context auditor roles from knowledge/orchestration/isolated-review.md's roster. Empty when the roster names none. */
  reviewedBy: RoleId[] = [],
): CatalogRole {
  const packs = ["context.founder-language" as ContextPackId, ...contextPackIds.filter((packId) => packId !== "context.founder-language")];
  return {
    id,
    name,
    promptPath: `agents/${prompt}.md`,
    contextOrigin: "workspace",
    scope,
    parentPromptPaths: [...parentPromptPaths],
    contextPackIds: packs,
    skillRoutes,
    toolRoutes,
    capabilityIds,
    outputPathPrefixes,
    ...(reviewedBy.length > 0 ? { reviewedBy } : {}),
  };
}

