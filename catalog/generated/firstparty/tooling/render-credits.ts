#!/usr/bin/env node
/**
 * render-credits.ts — project the public credit and legal-notice surfaces and the maintainer
 * support report from the canonical upstream metadata under `catalog/upstreams/` (ADR-0005).
 *
 * Inputs: `catalog/upstreams/<id>.yaml`, the verbatim notice texts under `notices/`, and the
 * recorded observations under `observations/`, all read through `loadUpstreams`. Any load issue
 * (invalid manifest, missing notice, notice digest mismatch) fails the render: a credit or a
 * notice is never rendered from metadata that did not validate.
 *
 * Outputs (repository-relative):
 * - `ACKNOWLEDGMENTS.md`: credits for upstreams with `credits.acknowledge: true`.
 * - `THIRD_PARTY_NOTICES.md`: verbatim notices for incorporated third-party material.
 * - `docs/upstreams/support-report.md`: the maintainer support and observation snapshot.
 * - `docs/upstreams/coverage-report.md`: source-link gaps in active bound knowledge.
 *
 * The output is deterministic. The only dates are the ones the manifests and observations carry.
 * Nothing here fetches, installs, or executes upstream code.
 *
 * npm scripts: render:credits (write), check:credits (report stale projections).
 * Usage: tsx tooling/render-credits.ts [--skill-root <path>] [--check] [--json]
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadKnowledgePackages } from "../catalog/knowledge-packages.js";
import { resolveSkillRoot } from "./lib/skill-root.js";
import { upstreamCoverage, renderUpstreamCoverage } from "../kernel/contribution/upstream-coverage.js";
import type { UpstreamManifest, UpstreamObservation, UpstreamRelationshipKind } from "../contracts/contribution/contract.js";
import { loadUpstreams, UPSTREAMS_DIRECTORY, type LoadedUpstream } from "../kernel/contribution/upstreams-load.js";
import { flagBoolean, flagString, issue, parseFlags, reportAndExit, type Issue } from "./lib/launch-state.js";

const ACKNOWLEDGMENTS_PATH = "ACKNOWLEDGMENTS.md";
const THIRD_PARTY_NOTICES_PATH = "THIRD_PARTY_NOTICES.md";
const SUPPORT_REPORT_PATH = "docs/upstreams/support-report.md";

const GENERATED_BY = `Generated by tooling/render-credits.ts from ${UPSTREAMS_DIRECTORY}. Edit the manifests, not this file.`;

/** Relationship kinds whose material reaches the builder's distribution and therefore needs its notice shipped. */
const INCORPORATING_KINDS = new Set<UpstreamRelationshipKind>([
  "external-executable",
  "copied-code",
  "template-or-asset",
  "adapted-method",
  "selected-skill-guidance",
]);

const defaultSkillRoot = resolveSkillRoot(import.meta.url);

function cell(value: string): string {
  return value.replace(/\r?\n/gu, " ").replace(/\|/gu, "\\|").trim();
}

function people(entries: ReadonlyArray<{ name: string; role: string }>): string {
  return entries.map((entry) => `${entry.name}, ${entry.role}`).join("; ");
}

function isoDatePlusDays(date: string, days: number): string {
  const base = new Date(`${date}T00:00:00Z`);
  base.setUTCDate(base.getUTCDate() + days);
  return base.toISOString().slice(0, 10);
}

function baselineLabel(baseline: { revision: string; observedAt: string } | undefined): string {
  return baseline ? `${baseline.revision}@${baseline.observedAt}` : "unknown";
}

function acknowledgmentEntry(manifest: UpstreamManifest): string[] {
  const authorNames = new Set(manifest.authors.map((author) => author.name));
  const maintainers = manifest.maintainers.filter((maintainer) => !authorNames.has(maintainer.name));
  const lines = [`**${manifest.project}**`, "", `- ${manifest.authors.length > 1 ? "Original authors" : "Original author"}: ${people(manifest.authors)}`];
  if (maintainers.length > 0) lines.push(`- ${maintainers.length > 1 ? "Current maintainers" : "Current maintainer"}: ${people(maintainers)}`);
  lines.push(
    `- License: ${manifest.license.spdx} (${manifest.license.status})`,
    `- Canonical URL: ${manifest.canonicalUrl}`,
    `- Contributes: ${manifest.credits.summary}`,
    "- How we consume it:",
    ...manifest.relationships.map((relationship) => `  - ${relationship.kind}: ${relationship.consumption}`),
    "",
  );
  return lines;
}

function renderAcknowledgments(upstreams: readonly LoadedUpstream[]): string {
  const credited = upstreams.map((entry) => entry.manifest).filter((manifest) => manifest.credits.acknowledge);
  const section = (title: string, uses: readonly string[]): string[] => {
    const members = credited.filter((manifest) => uses.includes(manifest.credits.use));
    return [`## ${title}`, "", ...(members.length ? members.flatMap(acknowledgmentEntry) : ["None recorded.", ""])];
  };
  return [
    "# Acknowledgments",
    "",
    "B2C App Builder is built on open-source work and adapts published methods. This file credits the projects and people that power it. It lists actual use or adaptation only, never candidates that were merely inspected. Legal notices are separate, in [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md).",
    "",
    ...section("Open-source projects we run or wrap", ["direct", "wrapped"]),
    ...section("Methods and guidance we adapted", ["adapted", "inspiration"]),
    ...section("Optional managed services", ["service"]),
    GENERATED_BY,
    "",
  ].join("\n");
}

function renderThirdPartyNotices(upstreams: readonly LoadedUpstream[]): string {
  const incorporating = upstreams.filter(
    (entry) => entry.notice && entry.manifest.relationships.some((relationship) => INCORPORATING_KINDS.has(relationship.kind)),
  );
  const serviceOnly = upstreams.filter((entry) => entry.manifest.relationships.every((relationship) => relationship.kind === "remote-service"));
  const entries = incorporating.flatMap((entry) => {
    const { manifest } = entry;
    const notice = entry.notice!;
    const text = notice.text.endsWith("\n") ? notice.text : `${notice.text}\n`;
    return [
      `## ${manifest.project}`,
      "",
      `- Upstream: ${manifest.canonicalUrl}`,
      `- License: ${manifest.license.spdx}`,
      `- Copyright: ${manifest.copyright ?? "unknown"}`,
      `- Scope: ${manifest.license.scope ?? "unknown"}`,
      "",
      "```text",
      `${text}\`\`\``,
      "",
      `Notice sha256: ${notice.sha256}`,
      "",
    ];
  });
  const services = serviceOnly.map((entry) => `${entry.manifest.project} (${entry.manifest.id})`);
  return [
    "# Third-party notices",
    "",
    "This file records the notices required for third-party material the builder distributes or incorporates beyond package-manager dependency metadata. npm dependencies keep their own license files under node_modules. Each notice below is copied byte for byte from the retained notice file named by its upstream manifest; the digest after the block identifies those bytes.",
    "",
    ...(entries.length ? entries : ["No incorporated third-party material is recorded.", ""]),
    `Services without incorporated material: ${services.length ? services.join("; ") : "none"}.`,
    "",
    GENERATED_BY,
    "",
  ].join("\n");
}

function installedExecutable(observation: UpstreamObservation | undefined): string {
  const host = observation?.host;
  if (!host || !host.selected) return "not observed";
  const selected = host.executables.find((executable) => executable.path === host.selected);
  return `${host.selected} ${selected?.version ?? "(unknown version)"}`;
}

function latestStable(observation: UpstreamObservation | undefined): string {
  if (!observation) return "unknown (no observation)";
  if (!observation.latestStable) return "unknown (observation records no stable release)";
  return `${observation.latestStable.tag} (published ${observation.latestStable.publishedAt.slice(0, 10)})`;
}

function supportRow(entry: LoadedUpstream): string {
  const { manifest, observation } = entry;
  const ranges = manifest.support.versions.map((version) => `\`${version.range}\` ${version.status}`).join("; ") || "none declared";
  const review = `${manifest.review.status}; last ${manifest.review.lastReview}; due ${isoDatePlusDays(manifest.review.lastReview, manifest.review.cadenceDays)}`;
  const owners = new Set(manifest.relationships.flatMap((relationship) => relationship.localOwners));
  const tests = new Set(manifest.relationships.flatMap((relationship) => relationship.tests));
  return `| ${[
    manifest.id,
    manifest.project,
    manifest.relationships.map((relationship) => relationship.kind).join(", "),
    baselineLabel(manifest.baselines.reviewedSource),
    baselineLabel(manifest.baselines.reviewedGuidance),
    ranges,
    latestStable(observation),
    observation ? observation.checkedAt.slice(0, 10) : "none",
    installedExecutable(observation),
    review,
    String(owners.size),
    String(tests.size),
  ]
    .map(cell)
    .join(" | ")} |`;
}

function supportSection(entry: LoadedUpstream): string[] {
  const { manifest, observation } = entry;
  const list = (items: readonly string[]): string[] => (items.length ? [...items, ""] : ["- None recorded.", ""]);
  return [
    `## ${manifest.id}`,
    "",
    `${manifest.project}. Canonical URL: ${manifest.canonicalUrl}`,
    "",
    "Unsupported operations:",
    "",
    ...list(manifest.support.unsupportedOperations.map((operation) => `- ${operation.id}: ${operation.reason}`)),
    "Intentional adaptations:",
    "",
    ...list(manifest.adaptations.map((adaptation) => `- ${adaptation.id}: ${adaptation.description} (owner: ${adaptation.owner})`)),
    observation ? `Unknowns (observation ${observation.checkedAt.slice(0, 10)}, method ${observation.method}):` : "Unknowns:",
    "",
    ...(observation ? list(observation.unknowns.map((unknown) => `- ${unknown}`)) : ["- No observation recorded.", ""]),
  ];
}

function renderSupportReport(upstreams: readonly LoadedUpstream[]): string {
  const header = [
    "Id",
    "Project",
    "Relationships",
    "Reviewed source",
    "Reviewed guidance",
    "Supported ranges",
    "Latest observed stable",
    "Observed",
    "Installed executable",
    "Review",
    "Local owners",
    "Tests",
  ];
  return [
    "# Upstream support report",
    "",
    `Generated from ${UPSTREAMS_DIRECTORY} for maintainers. It states what the builder supports for each upstream and what it has observed. It is distinct from ACKNOWLEDGMENTS.md, which credits projects, and from THIRD_PARTY_NOTICES.md, which carries legal notices. \`b2c contribute upstreams\` is the live read model over the same manifests; this file is the committed snapshot. Unknown values stay unknown. An observation is a dated read, not proof of currency.`,
    "",
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...upstreams.map(supportRow),
    "",
    ...upstreams.flatMap(supportSection),
    GENERATED_BY,
    "",
  ].join("\n");
}

function main(): void {
  const flags = parseFlags(process.argv.slice(2), [
    { flags: ["--skill-root", "--root"], key: "skillRoot" },
    { flags: ["--check"], key: "check", kind: "boolean" },
    { flags: ["--json"], key: "json", kind: "boolean" },
  ]);
  const skillRoot = path.resolve(flagString(flags, "skillRoot") ?? defaultSkillRoot);
  const check = flagBoolean(flags, "check");
  const json = flagBoolean(flags, "json");
  const issues: Issue[] = [];

  const loaded = loadUpstreams(skillRoot);
  if (loaded.issues.length > 0) {
    for (const loadIssue of loaded.issues) issues.push(issue("error", loadIssue.code, loadIssue.message, loadIssue.path));
    reportAndExit("Credits projections", issues);
    return;
  }
  const upstreams = [...loaded.upstreams].sort((left, right) => left.manifest.id.localeCompare(right.manifest.id));

  const rendered: string[] = [];
  const unchanged: string[] = [];
  const emit = (relative: string, content: string): void => {
    const file = path.join(skillRoot, relative);
    let current: string | undefined;
    try {
      current = readFileSync(file, "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    }
    if (current === content) {
      unchanged.push(relative);
      return;
    }
    if (check) {
      issues.push(issue("error", "credits.stale_projection", `Stale credits projection: ${relative}`, relative, { fixHint: "Run npm run render:credits." }));
      return;
    }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, content, "utf8");
    rendered.push(relative);
  };

  emit(ACKNOWLEDGMENTS_PATH, renderAcknowledgments(upstreams));
  emit(THIRD_PARTY_NOTICES_PATH, renderThirdPartyNotices(upstreams));
  emit(SUPPORT_REPORT_PATH, renderSupportReport(upstreams));
  let ownRepository: string | undefined;
  try {
    const pkg = JSON.parse(readFileSync(path.join(skillRoot, "package.json"), "utf8")) as { repository?: string | { url?: string } };
    ownRepository = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  emit(
    "docs/upstreams/coverage-report.md",
    renderUpstreamCoverage(
      upstreamCoverage(
        loadKnowledgePackages(skillRoot),
        upstreams.map((entry) => entry.manifest),
        ownRepository,
      ),
    ),
  );

  if (check) {
    reportAndExit("Credits projections", issues);
    return;
  }
  if (json) {
    process.stdout.write(`${JSON.stringify({ pass: true, manifests: upstreams.length, rendered, unchanged })}\n`);
    return;
  }
  console.log(`Rendered credits from ${upstreams.length} upstream manifest(s): ${rendered.length} written, ${unchanged.length} unchanged.`);
}

main();
